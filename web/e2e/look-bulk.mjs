// ad-hoc: on a running app, duplicate a network, open the copy in the editor, delete every node matching a search
// (more than 60), check the count, undo, and screenshot each step. node e2e/look-bulk.mjs <outdir> <network-id> <query>
import { chromium } from '@playwright/test';
const [out, net, q] = process.argv.slice(2);
const base = process.env.MPN_URL ?? 'http://127.0.0.1:8871/';
const api = async (path, body) => (await fetch(base + path, body === undefined ? {} : { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })).json();
const wait = async (t) => { while (t.state === 'running') { await new Promise((r) => setTimeout(r, 300)); t = await api(`api/library/tasks/${t.id}`); } return t; };
const copy = (await wait(await api(`api/library/networks/${net}/duplicate`, { name: 'Bulk delete test copy' }))).result;
console.log('copy', copy.id, copy.nodes, 'nodes');
const b = await chromium.launch({ channel: 'chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
p.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
await p.goto(base);
await p.getByRole('button', { name: 'MPN networks' }).click();
await p.getByRole('row', { name: /Bulk delete test copy/ }).getByRole('button', { name: 'Edit' }).click();
await p.getByRole('combobox', { name: 'Search nodes' }).waitFor({ timeout: 30000 });
await p.waitForTimeout(1500);
const before = await api('api/status');
await p.getByRole('combobox', { name: 'Search nodes' }).fill(q);
await p.getByRole('button', { name: 'Delete all…' }).waitFor();
await p.screenshot({ path: `${out}/bulk-search.png` });
await p.getByRole('button', { name: 'Delete all…' }).click();
await p.getByRole('button', { name: /^Delete [\d,]+ nodes$/ }).waitFor();
await p.screenshot({ path: `${out}/bulk-dialog.png` });
const label = await p.getByRole('button', { name: /^Delete [\d,]+ nodes$/ }).innerText();
const t0 = Date.now();
await p.getByRole('button', { name: /^Delete [\d,]+ nodes$/ }).click();
await p.getByText(/^Deleted [\d,]+ nodes in revision/).waitFor({ timeout: 60000 });
const ms = Date.now() - t0;
await p.screenshot({ path: `${out}/bulk-done.png` });
const after = await api('api/status');
const left = await api('api/nodes/select', { filter: { q } });
await p.getByRole('button', { name: 'Undo', exact: true }).last().click();
await p.getByText(/^Restored\. Now at revision/).waitFor({ timeout: 30000 });
const restored = await api('api/status');
console.log(`${label}: ${ms} ms in the UI; live nodes ${before.counts.canonical_live_nodes} -> ${after.counts.canonical_live_nodes} -> ${restored.counts.canonical_live_nodes} after undo; still matching after delete: ${left.count}`);
await p.screenshot({ path: `${out}/bulk-undone.png` });
console.log(logs.join('\n') || 'no page errors');
await b.close();
await api('api/desktop/project/close', {});
const del = await (await fetch(base + `api/library/networks/${copy.id}`, { method: 'DELETE' })).json();
console.log('copy moved to trash:', !!del.moved_to);
